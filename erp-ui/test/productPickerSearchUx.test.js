const assert = require("assert")
const fs = require("fs")
const path = require("path")

const uiRoot = path.resolve(__dirname, "..")
const repoRoot = path.resolve(uiRoot, "..")
const readUi = file => fs.readFileSync(path.resolve(uiRoot, file), "utf8")
const readRepo = file => fs.readFileSync(path.resolve(repoRoot, file), "utf8")

const productSelect = readUi("src/views/inventory/components/ProductSelect.vue")
const inventoryItemSelect = readUi("src/views/inventory/components/InventoryItemSelect.vue")
const purchasePage = readUi("src/views/inventory/purchase/index.vue")
const salesPage = readUi("src/views/inventory/sales/index.vue")
const transferPage = readUi("src/views/inventory/transfer/index.vue")
const fixedAssetConfig = readUi("src/views/oa/fixedAsset/config/index.vue")
const mobilePicker = readUi("src/views/mobile/feature/components/MobileEntityPicker.vue")
const mobileEntityService = readUi("src/views/mobile/feature/mobileEntityService.js")
const mobileSearchConfigs = readUi("src/views/mobile/feature/featureSearchConfigs.js")
const productDomain = readRepo("erp-modules/erp-inventory/src/main/java/com/erp/inventory/domain/InvProduct.java")
const productMapper = readRepo("erp-modules/erp-inventory/src/main/resources/mapper/inventory/InvProductMapper.xml")
const stockMapper = readRepo("erp-modules/erp-inventory/src/main/resources/mapper/inventory/InvStockMapper.xml")
const mobileMapper = readRepo("erp-modules/erp-inventory/src/main/resources/mapper/inventory/InvMobileMapper.xml")
const purchaseService = readRepo("erp-modules/erp-inventory/src/main/java/com/erp/inventory/service/impl/InvPurchaseServiceImpl.java")

assert.ok(productSelect.includes('placeholder: { type: String, default: "搜索商品名称/编码" }'), "shared product select should keep the old default placeholder")
assert.ok(productSelect.includes("keywordSearch: { type: Boolean, default: false }"), "shared product select keyword search should be opt-in")
assert.ok(productSelect.includes("showContextMeta: { type: Boolean, default: false }"), "shared product select richer option meta should be opt-in")
assert.ok(productSelect.includes("if (this.keywordSearch)"), "shared product select should guard keyword search behind the opt-in prop")
assert.ok(productSelect.includes("productName: keyword"), "shared product select should preserve legacy product-name search for warehouse defaults")
assert.ok(productSelect.includes("productCode: keyword"), "shared product select should preserve legacy product-code search for warehouse defaults")
assert.ok(!productSelect.includes("supplierName"), "shared product select should not expose supplier fields")
assert.ok(!productSelect.includes("供应商"), "shared product select should not show supplier text")
assert.ok(!productSelect.includes("sku"), "shared product select should not expose SKU")

assert.ok(salesPage.includes('placeholder="搜索物料名称/编码"'), "inventory sales item select should explain supported fields")
assert.ok(salesPage.includes("<inventory-item-select"), "inventory sales should use the generic item selector")
assert.ok(salesPage.includes('["product", "gift"]'), "inventory sales should expose product and gift choices")
assert.ok(!salesPage.includes("scope.row.sku ||"), "sales detail display should not show SKU")
assert.ok(!salesPage.includes("item.productCode || item.sku"), "sales edit product meta should not fall back to SKU")

assert.ok(purchasePage.includes('class="app-container warehouse-page"'), "purchase page is a warehouse-management page")
assert.ok(purchasePage.includes("productQuery.productName"), "warehouse purchase picker should keep the old product-name query")
assert.ok(purchasePage.includes("productQuery.supplierName"), "warehouse purchase picker should keep the old supplier query")
assert.ok(!purchasePage.includes("productQuery.keyword"), "warehouse purchase picker should not receive inventory keyword changes")
assert.ok(!purchasePage.includes("productQuery.categoryId"), "warehouse purchase picker should not receive inventory category changes")
assert.ok(!purchasePage.includes("categoryTree"), "warehouse purchase picker should not load inventory category filters")

const transferStockPickerBinding = ':visible.sync="stockPickerOpen"'
const transferStockPickerBindingIndex = transferPage.indexOf(transferStockPickerBinding)
const transferStockPickerStart = transferPage.lastIndexOf("<el-dialog", transferStockPickerBindingIndex)
const transferStockPickerEnd = transferPage.indexOf("</el-dialog>", transferStockPickerBindingIndex)
assert.ok(
  transferStockPickerBindingIndex >= 0 &&
    transferStockPickerStart >= 0 &&
    transferStockPickerEnd > transferStockPickerBindingIndex,
  "warehouse transfer page should keep its stock picker dialog"
)
const transferStockDialog = transferPage.slice(transferStockPickerStart, transferStockPickerEnd)
assert.ok(transferStockDialog.includes("选择返仓库存"), "warehouse transfer stock picker should label the return context")
assert.ok(transferStockDialog.includes("选择调出店库存"), "warehouse transfer stock picker should label the cross-store context")
assert.ok(transferStockDialog.includes("选择要货库存"), "warehouse transfer stock picker should label the warehouse context")
assert.ok(transferStockDialog.includes('placeholder="搜索商品名称/编码"'), "warehouse transfer stock picker should keep the old product search placeholder")
assert.ok(transferStockDialog.includes('@search-keyword-change="handleStockKeywordChange"'), "warehouse transfer stock picker should capture unselected fuzzy-search text")
assert.ok(transferStockDialog.includes('row-key="stockId"'), "warehouse transfer stock picker should expose a stable row key")
assert.ok(transferStockDialog.includes(':reserve-selection="true"'), "warehouse transfer stock picker should preserve checked rows across paging and searching")
assert.ok(!transferStockDialog.includes("商品名称/编码/规格"), "warehouse transfer stock picker should not receive inventory spec-search copy")
assert.ok(transferStockDialog.includes('label="分类"'), "warehouse transfer stock picker should expose category filtering")
assert.ok(transferPage.includes("stockQuery.categoryId"), "warehouse transfer stock picker should pass category query state")
assert.ok(transferPage.includes("handleStockCategoryChange"), "warehouse transfer stock picker should reset pagination when category changes")
assert.ok(transferPage.includes('query.productName = keyword'), "warehouse transfer stock picker should send typed text to the stock fuzzy-search contract")
assert.ok(transferPage.includes("delete query.itemId"), "typed fuzzy text should take precedence over a previously selected exact item")
assert.ok(transferPage.includes("categoryTree"), "warehouse transfer page should load inventory category filters")
assert.ok(inventoryItemSelect.includes('this.$emit("search-keyword-change", keyword)'), "generic inventory item select should expose its typed remote-search keyword")
assert.ok(inventoryItemSelect.includes('this.$emit("search-keyword-change", "")'), "selecting or clearing an exact item should clear stale fuzzy-search text")

assert.ok(fixedAssetConfig.includes('placeholder="请选择OE器皿，可输入名称或编码搜索"'), "fixed asset add-details OE search is outside inventory product-picker scope and should keep asset-specific copy")
assert.ok(fixedAssetConfig.includes("oeItemName: keyword"), "fixed asset OE search should keep asset-specific name query")
assert.ok(!fixedAssetConfig.includes("productOptionLabel"), "fixed asset product options should not receive inventory picker changes")
assert.ok(!fixedAssetConfig.includes("keyword: keyword"), "fixed asset product search should not receive inventory keyword changes")

assert.ok(!mobilePicker.includes("搜索商品名称/编码/规格"), "mobile shared picker is outside this desktop inventory scope")
assert.ok(mobileEntityService.includes("keyword ? { productName: keyword } : {}"), "mobile product fallback should keep old product-name query")
assert.ok(mobileSearchConfigs.includes('{ key: "supplierName", label: "供应商" }'), "mobile warehouse-related search configs should remain unchanged")

assert.ok(productDomain.includes("private String keyword;"), "product API should expose keyword for inventory opt-in search")
assert.ok(productMapper.includes("keyword != null and keyword != ''"), "product list mapper should support opt-in keyword search")
assert.ok(productMapper.includes("p.product_name like concat('%', #{keyword}, '%')"), "product keyword should match name")
assert.ok(productMapper.includes("p.product_code like concat('%', #{keyword}, '%')"), "product keyword should match code")
assert.ok(productMapper.includes("p.spec like concat('%', #{keyword}, '%')"), "product keyword should match spec")
assert.ok(productMapper.includes("p.sku like concat('%', #{sku}, '%')"), "existing explicit SKU filter should remain available for unchanged pages")
assert.ok(stockMapper.includes("p.product_name like concat('%', #{productName}, '%')"), "stock fuzzy query should match product names")
assert.ok(stockMapper.includes("p.product_code like concat('%', #{productName}, '%')"), "stock fuzzy query should also match product codes")
assert.ok(!productMapper.includes("p.supplier_name like concat('%', #{keyword}, '%')"), "inventory keyword search should not expose supplier")
assert.ok(mobileMapper.includes("or p.sku like concat('%', #{keyword}, '%')"), "mobile compact product search should remain unchanged")
assert.ok(!mobileMapper.includes("or p.spec like concat('%', #{keyword}, '%')"), "mobile compact product search should not receive this desktop inventory change")
assert.ok(purchaseService.includes("未绑定供应商"), "warehouse purchase service messages should remain unchanged")

